import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu', '--disable-dawn-features=disallow_unsafe_apis'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('button', { name: "Let's play" }).waitFor({ timeout: 30000 });
  assert.deepEqual(await page.locator('#game').boundingBox(), { x: 0, y: 0, width: 1440, height: 1050 });
  assert.equal(await page.locator('.topbar, .intro, .under-game, .bottom').count(), 0);
  await page.screenshot({ path: 'qa-desktop.png', fullPage: true });
  await page.getByRole('button', { name: "Let's play" }).click();
  await page.keyboard.down('ArrowRight'); await page.waitForTimeout(750); await page.keyboard.up('ArrowRight');
  assert.match(await page.locator('#coins').innerText(), /01/);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Keep going' }).waitFor();
  const time = await page.locator('#time').innerText(); await page.waitForTimeout(1100); assert.equal(await page.locator('#time').innerText(), time);
  await page.getByRole('button', { name: 'Keep going' }).click();
  await page.keyboard.press('KeyR');
  await page.waitForFunction(() => document.querySelector('#coins').textContent.trim().startsWith('00'));
  assert.match(await page.locator('#coins').innerText(), /00/);
  await page.keyboard.down('ArrowRight'); await page.keyboard.down('Space');
  await page.waitForTimeout(500); await page.keyboard.up('Space'); await page.keyboard.up('ArrowRight');
  await page.screenshot({ path: 'qa-playing.png', fullPage: true });
  await page.getByRole('button', { name: 'Enable sound' }).click();
  await page.getByRole('button', { name: 'Mute sound' }).waitFor();
  await page.getByRole('button', { name: 'How to play' }).click();
  await page.getByRole('heading', { name: 'A hop, skip & a jump.' }).waitFor();
  await page.getByRole('button', { name: "Let's play" }).click();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  await mobile.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto('http://127.0.0.1:5173/');
  await mobile.getByRole('button', { name: "Let's play" }).waitFor({ timeout: 30000 });
  assert.deepEqual(await mobile.locator('#game').boundingBox(), { x: 0, y: 0, width: 390, height: 844 });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: 'qa-mobile.png', fullPage: true });
  await mobile.getByRole('button', { name: "Let's play" }).click();
  assert.ok(await mobile.getByRole('button', { name: 'Move right' }).isVisible());
  const move = await mobile.getByRole('button', { name: 'Move right' }).boundingBox();
  await mobile.mouse.move(move.x + move.width / 2, move.y + move.height / 2); await mobile.mouse.down();
  await mobile.waitForTimeout(750); await mobile.mouse.up();
  assert.match(await mobile.locator('#coins').innerText(), /01/);
  assert.deepEqual(errors, []);
  console.log('PASS: WebGPU render, coin pickup, jump, pause/resume, restart, sound, help, mobile controls and layout.');
} finally { await browser.close(); }
